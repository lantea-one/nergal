import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const directory = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(directory, "../../src/Nergal.Web/wwwroot/js/code-editor.bundle.js");
const result = await build({
  absWorkingDir: directory, entryPoints: ["code-editor.js"], bundle: true,
  minify: true, format: "iife", target: ["es2022"], write: false, metafile: true,
  banner: { js: "/* Generated by tools/web-assets/build.mjs. Third-party licenses: code-editor.LICENSE.txt */" },
});
const packages = new Set(Object.keys(result.metafile.inputs).map(input => {
  const parts = input.split("/");
  if (parts[0] !== "node_modules") return null;
  return parts[1].startsWith("@") ? parts.slice(1, 3).join("/") : parts[1];
}).filter(Boolean));
let notices = "Third-party packages bundled in code-editor.bundle.js\n\n";
for (const name of [...packages].sort()) {
  const root = path.join(directory, "node_modules", name);
  const metadata = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const license = await readFile(path.join(root, "LICENSE"), "utf8");
  notices += `${name} ${metadata.version}\n${license.trim()}\n\n`;
}
for (const [filename, content] of [[output, result.outputFiles[0].text], [output.replace(".bundle.js", ".LICENSE.txt"), notices]]) {
  if (process.argv.includes("--verify")) {
    if (await readFile(filename, "utf8") !== content) throw new Error(`Stale generated asset: ${filename}`);
  } else await writeFile(filename, content);
}
console.log(process.argv.includes("--verify") ? "Verified code editor bundle and licenses." : "Built code editor bundle and licenses.");
