-- Fingerprint structural metadata for the selected database. Omit the database
-- name, trigger definer and creation context's database collation, mutable
-- statistics, timestamps, and current AUTO_INCREMENT counters.
SELECT CAST(definition AS CHAR CHARACTER SET utf8mb4) AS definition
FROM (
    SELECT JSON_ARRAY('table', TABLE_NAME, TABLE_TYPE, ENGINE, ROW_FORMAT,
                      TABLE_COLLATION, CREATE_OPTIONS, TABLE_COMMENT) AS definition
    FROM information_schema.TABLES
    WHERE TABLE_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('partition', TABLE_NAME, PARTITION_NAME, SUBPARTITION_NAME,
                      PARTITION_ORDINAL_POSITION, SUBPARTITION_ORDINAL_POSITION,
                      PARTITION_METHOD, SUBPARTITION_METHOD, PARTITION_EXPRESSION,
                      SUBPARTITION_EXPRESSION, PARTITION_DESCRIPTION)
    FROM information_schema.PARTITIONS
    WHERE TABLE_SCHEMA = DATABASE() AND PARTITION_NAME IS NOT NULL

    UNION ALL
    SELECT JSON_ARRAY('column', TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME,
                      COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, CHARACTER_SET_NAME,
                      COLLATION_NAME, EXTRA, GENERATION_EXPRESSION, COLUMN_COMMENT)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('index', TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX, COLUMN_NAME,
                      NON_UNIQUE, COLLATION, SUB_PART, INDEX_TYPE, INDEX_COMMENT, IGNORED)
    FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('constraint', TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE)
    FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('constraint-column', TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION,
                      COLUMN_NAME, POSITION_IN_UNIQUE_CONSTRAINT,
                      CASE
                          WHEN REFERENCED_TABLE_SCHEMA IS NULL THEN NULL
                          WHEN REFERENCED_TABLE_SCHEMA = DATABASE() THEN 'local'
                          ELSE 'external'
                      END,
                      REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME)
    FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('foreign-key', TABLE_NAME, CONSTRAINT_NAME, UNIQUE_CONSTRAINT_NAME,
                      MATCH_OPTION, UPDATE_RULE, DELETE_RULE, REFERENCED_TABLE_NAME)
    FROM information_schema.REFERENTIAL_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('check', TABLE_NAME, CONSTRAINT_NAME, LEVEL, CHECK_CLAUSE)
    FROM information_schema.CHECK_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = DATABASE()

    UNION ALL
    SELECT JSON_ARRAY('trigger', EVENT_OBJECT_TABLE, TRIGGER_NAME, ACTION_TIMING,
                      EVENT_MANIPULATION, ACTION_ORDER, ACTION_ORIENTATION, ACTION_STATEMENT,
                      SQL_MODE, CHARACTER_SET_CLIENT, COLLATION_CONNECTION)
    FROM information_schema.TRIGGERS
    WHERE TRIGGER_SCHEMA = DATABASE()
) AS catalog
-- Sort fixed-width keys so the server's long-text sort limit cannot affect the order.
ORDER BY CAST(SHA2(definition, 256) AS BINARY(64));
